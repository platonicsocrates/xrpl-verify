#!/usr/bin/env python3
"""Generate proof/theories/HarnessCode.v: one fetch fact and one decode fact
for every instruction of the test binary.

The instruction words are read from the memory image (the .hex file that
elf-snapshot wrote), not from the ELF file. Each decoded form is computed by
Rocq with the model's own decoder, and each generated lemma is then checked
by Rocq when the file compiles. So nothing here is trusted: a wrong fact
does not compile.

Usage: gen-code-facts.py <theories-dir> <text-lo-hex> <text-hi-hex>
Needs `rocq` on PATH with LinuxProcessSemantics installed.
"""
import os
import subprocess
import sys
import tempfile

HEADER = '''\
(** * Fetch and decode facts for the test binary.

    GENERATED by tools/gen-code-facts.py from the memory image
    (HarnessMemImage.v and its .hex files). Do not edit.

    For each instruction at address A there are two lemmas:
      F_A  the model fetches this 32-bit word at A
      D_A  the model's decoder reads that word as this instruction
    Rocq checks both by computation, so none of this is trusted. *)

From Stdlib Require Import NArith ZArith List.
From LinuxProcessSemantics.LinuxProcessSem Require Import BvBase RiscvSemantics MemImageType.
From XrplVerify Require Import HarnessMemImage.
From LinuxProcessSemantics.Riscv Require Import Prelude Instr Decode DecodeC.
From LinuxProcessSemantics.Common Require Import StepTac.
Import ListNotations.
Open Scope bv_scope.

Definition harness_segs := HarnessMemImage_loaded_segments.
Definition harness_phdrs := HarnessMemImage_phdrs.
Global Strategy 200 [harness_segs].

Ltac vm_refl := vm_refl_bv.
'''


def decode(words):
    lines = [
        "From LinuxProcessSemantics.Riscv Require Import Prelude Instr Decode DecodeC.",
        "Open Scope bv_scope.",
        "Set Printing Depth 10000.", "Set Printing Width 10000.",
    ]
    lines += [f"Compute (decode_any (Z_to_bv 32 {w}))." for w in words]
    with tempfile.TemporaryDirectory() as tmp:
        with open(os.path.join(tmp, "d.v"), "w") as f:
            f.write("\n".join(lines) + "\n")
        # LPS_LOADPATH: an uninstalled build tree of the model, if any.
        lp = os.environ.get("LPS_LOADPATH")
        extra = ["-Q", lp, "LinuxProcessSemantics"] if lp else []
        out = subprocess.run(["rocq", "c"] + extra + ["d.v"], cwd=tmp,
                             check=True, capture_output=True, text=True).stdout
    results, cur = [], None
    for line in out.splitlines():
        s = line.strip()
        if s.startswith("= "):
            cur = s[2:]
        elif cur is not None and s.startswith(":"):
            results.append(cur.strip())
            cur = None
        elif cur is not None:
            cur += " " + s
    assert len(results) == len(words), (len(results), len(words))
    return dict(zip(words, results))


def main():
    theories, lo, hi = sys.argv[1], int(sys.argv[2], 16), int(sys.argv[3], 16)
    seg_base = 0x11000  # the r-x segment, HarnessMemImage_segment_001
    with open(os.path.join(theories, "HarnessMemImage_seg_001.hex")) as f:
        data = bytes.fromhex(f.read().strip())
    words = [int.from_bytes(data[a - seg_base:a - seg_base + 4], "little")
             for a in range(lo, hi, 4)]
    dec = decode(sorted({w for w in words if w != 0x73}))
    out = [HEADER]
    for i, w in enumerate(words):
        pc = lo + 4 * i
        out.append(f"Lemma F_{pc:x} : fetch_word harness_segs {pc:#x} = Some {w}."
                   " Proof. vm_refl. Qed.")
        if w != 0x73:  # ecall goes to the system-call layer, not the decoder
            out.append(f"Lemma D_{pc:x} : decode_any (Z_to_bv 32 {w}) = {dec[w]}."
                       " Proof. vm_refl. Qed.")
    with open(os.path.join(theories, "HarnessCode.v"), "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {len(words)} instructions")


if __name__ == "__main__":
    main()
